// Per-project traffic capture. Once a project has a custom domain, its traffic
// flows browser → nginx → app and never touches the repo-server. So we make
// nginx log each project's requests to its own file (JSON format) and tail it
// here to build per-project graphs + a packet feed.

func logDir() string { return filepath.Join(installDir, "logs") }

func projectLogPath(domain string) string {
	return filepath.Join(logDir(), domain+".log")
}

// nginxLogFormat is written once to /etc/nginx/conf.d so the access_log
// directives in each site config can reference it.
const nginxLogFormat = `# Generated by Sixter — per-project JSON access log format
log_format sixter_json escape=json
  '{"t":"$time_iso8601","ip":"$remote_addr","m":"$request_method",'
  '"p":"$request_uri","s":$status,"b":$body_bytes_sent,"d":$request_time}';
`

type projCap struct {
	mu       sync.Mutex
	minutes  map[int64]*minuteStat
	packets  []pktEntry
	seq      int64
	topPaths map[string]int64
	topIPs   map[string]int64
	tailing  bool
}

var (
	projCapMu sync.Mutex
	projCaps  = map[string]*projCap{}
)

func captureForProject(name string) *projCap {
	projCapMu.Lock()
	defer projCapMu.Unlock()
	c := projCaps[name]
	if c == nil {
		c = &projCap{
			minutes:  map[int64]*minuteStat{},
			topPaths: map[string]int64{},
			topIPs:   map[string]int64{},
		}
		projCaps[name] = c
	}
	return c
}

// nginx log line shape (parsed from the built-in "combined" format)
type nginxLine struct {
	T  string
	IP string
	M  string
	P  string
	S  int
	B  int64
	D  float64
}

// combinedRe parses nginx's default "combined" log format:
//   1.2.3.4 - - [10/Jun/2026:12:00:00 +0000] "GET /path HTTP/1.1" 200 1234 "ref" "ua"
var combinedRe = regexp.MustCompile(`^(\S+) \S+ \S+ \[([^\]]+)\] "(\S+) (\S+)[^"]*" (\d{3}) (\d+|-)`)

// parseCombined turns one combined-format log line into an nginxLine.
func parseCombined(line string) (nginxLine, bool) {
	m := combinedRe.FindStringSubmatch(line)
	if m == nil {
		return nginxLine{}, false
	}
	status, _ := strconv.Atoi(m[5])
	bytes := int64(0)
	if m[6] != "-" {
		bytes, _ = strconv.ParseInt(m[6], 10, 64)
	}
	return nginxLine{
		IP: m[1],
		T:  m[2], // e.g. 10/Jun/2026:12:00:00 +0000
		M:  m[3],
		P:  m[4],
		S:  status,
		B:  bytes,
	}, true
}

func (c *projCap) add(l nginxLine) {
	c.mu.Lock()
	defer c.mu.Unlock()

	c.seq++
	ts := time.Now()
	if t, err := time.Parse("02/Jan/2006:15:04:05 -0700", l.T); err == nil {
		ts = t
	}
	c.packets = append(c.packets, pktEntry{
		ID:        c.seq,
		Time:      ts.Format("15:04:05"),
		Src:       l.IP,
		Method:    l.M,
		Host:      "",
		Path:      l.P,
		Status:    l.S,
		RespBytes: l.B,
		DurMs:     l.D * 1000.0,
	})
	if len(c.packets) > 1000 {
		c.packets = c.packets[len(c.packets)-1000:]
	}

	minKey := ts.Unix() / 60
	m, ok := c.minutes[minKey]
	if !ok {
		m = &minuteStat{T: minKey * 60}
		c.minutes[minKey] = m
		cutoff := minKey - 60
		for k := range c.minutes {
			if k < cutoff {
				delete(c.minutes, k)
			}
		}
	}
	m.Requests++
	m.Bytes += l.B

	if len(c.topPaths) < 500 || c.topPaths[l.P] > 0 {
		c.topPaths[l.P]++
	}
	if len(c.topIPs) < 500 || c.topIPs[l.IP] > 0 {
		c.topIPs[l.IP]++
	}
}

// addLive records a request the repo-server served itself. Tunnel-mode traffic
// never touches nginx, so there is no access log to tail — we're inline, so we
// feed the very same capture directly and the dashboard looks identical in
// both modes.
func (c *projCap) addLive(ip, method, path string, status int, respBytes int64, durMs float64, at time.Time) {
	c.mu.Lock()
	defer c.mu.Unlock()

	c.seq++
	c.packets = append(c.packets, pktEntry{
		ID:        c.seq,
		Time:      at.Format("15:04:05"),
		Src:       ip,
		Method:    method,
		Host:      "",
		Path:      path,
		Status:    status,
		RespBytes: respBytes,
		DurMs:     durMs,
	})
	if len(c.packets) > 1000 {
		c.packets = c.packets[len(c.packets)-1000:]
	}

	minKey := at.Unix() / 60
	m, ok := c.minutes[minKey]
	if !ok {
		m = &minuteStat{T: minKey * 60}
		c.minutes[minKey] = m
		cutoff := minKey - 60
		for k := range c.minutes {
			if k < cutoff {
				delete(c.minutes, k)
			}
		}
	}
	m.Requests++
	m.Bytes += respBytes

	if len(c.topPaths) < 500 || c.topPaths[path] > 0 {
		c.topPaths[path]++
	}
	if len(c.topIPs) < 500 || c.topIPs[ip] > 0 {
		c.topIPs[ip]++
	}
}

// recordTunnelRequest attributes a tunnel-mode request to its project and files
// it in that project's capture. Called from the root handler after the reverse
// proxy (or static file server) has finished.
func recordTunnelRequest(r *http.Request, status int, respBytes int64, dur time.Duration) {
	host := r.Host
	if i := strings.IndexByte(host, ':'); i >= 0 {
		host = host[:i]
	}
	project := projectForDomain(strings.ToLower(host))
	if project == "" {
		return
	}
	captureForProject(project).addLive(
		captureClientIP(r), r.Method, r.URL.Path, status, respBytes,
		float64(dur.Microseconds())/1000.0, time.Now(),
	)
}

// projectForDomain reverse-maps an attached domain to its project.
func projectForDomain(domain string) string {
	domainsMu.Lock()
	defer domainsMu.Unlock()
	for project, cfg := range domains {
		if cfg != nil && strings.EqualFold(cfg.Domain, domain) {
			return project
		}
	}
	return ""
}

// captureClientIP resolves the real visitor IP. In tunnel mode the request
// arrives via the Sixter gateway, so the forwarded header is the visitor and
// RemoteAddr is our own edge.
func captureClientIP(r *http.Request) string {
	if xff := r.Header.Get("X-Forwarded-For"); xff != "" {
		if i := strings.IndexByte(xff, ','); i > 0 {
			return strings.TrimSpace(xff[:i])
		}
		return strings.TrimSpace(xff)
	}
	if rip := strings.TrimSpace(r.Header.Get("X-Real-IP")); rip != "" {
		return rip
	}
	if host, _, err := net.SplitHostPort(r.RemoteAddr); err == nil {
		return host
	}
	return r.RemoteAddr
}

// startProjectTail tails a project's nginx log in the background. Safe to call
// repeatedly — it starts at most one tailer per project.
func startProjectTail(project, domain string) {
	// Tunnel-mode domains are served by us, not nginx: there is no access log
	// to tail (the tailer would retry a missing file forever). Their traffic is
	// captured inline by recordTunnelRequest instead.
	if isTunnelHost(domain) {
		return
	}
	c := captureForProject(project)
	c.mu.Lock()
	if c.tailing {
		c.mu.Unlock()
		return
	}
	c.tailing = true
	c.mu.Unlock()

	go tailLog(c, projectLogPath(domain))
}

func tailLog(c *projCap, path string) {
	var offset int64
	for {
		f, err := os.Open(path)
		if err != nil {
			time.Sleep(3 * time.Second)
			continue
		}
		// if the file shrank (rotation), restart from the top
		if st, serr := f.Stat(); serr == nil && st.Size() < offset {
			offset = 0
		}
		_, _ = f.Seek(offset, 0)
		sc := bufio.NewScanner(f)
		sc.Buffer(make([]byte, 64*1024), 1024*1024)
		for sc.Scan() {
			if l, ok := parseCombined(sc.Text()); ok {
				c.add(l)
			}
		}
		if st, serr := f.Stat(); serr == nil {
			offset = st.Size()
		}
		_ = f.Close()
		time.Sleep(1 * time.Second)
	}
}

// projectStats snapshots a project's capture for the API.
func (c *projCap) snapshot() map[string]any {
	c.mu.Lock()
	defer c.mu.Unlock()

	now := time.Now().Unix() / 60
	series := make([]minuteStat, 0, 60)
	for i := int64(59); i >= 0; i-- {
		key := now - i
		if m, ok := c.minutes[key]; ok {
			series = append(series, *m)
		} else {
			series = append(series, minuteStat{T: key * 60})
		}
	}

	out := make([]pktEntry, len(c.packets))
	copy(out, c.packets)
	for i, j := 0, len(out)-1; i < j; i, j = i+1, j-1 {
		out[i], out[j] = out[j], out[i]
	}
	if len(out) > 200 {
		out = out[:200]
	}

	var total int64
	for _, m := range series {
		total += m.Requests
	}

	return map[string]any{
		"minutes":  series,
		"packets":  out,
		"topPaths": topN(c.topPaths, 8),
		"total":    total,
	}
}
