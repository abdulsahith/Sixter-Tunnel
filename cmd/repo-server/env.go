package main

// Per-project environment variables. Production backends need configuration
// (DB URLs, API keys, secrets). We persist them to a 0600 env file and inject
// them into the app's systemd unit via EnvironmentFile, so a redeploy/restart
// picks them up. The dashboard reads/writes them after type detection.

import (
	"bufio"
	"encoding/json"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var envKeyRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func envDir() string                    { return filepath.Join(installDir, "env") }
func envFilePath(project string) string { return filepath.Join(envDir(), project+".env") }

// projectFromDir maps a working directory back to its project name.
// Projects live at <dataDir>/<project>[/subfolder], so the first path
// component after dataDir is the project. Returns "" for anything outside.
func projectFromDir(dir string) string {
	rel, err := filepath.Rel(dataDir, dir)
	if err != nil {
		return ""
	}
	rel = filepath.ToSlash(rel)
	if rel == "." || strings.HasPrefix(rel, "../") || rel == ".." {
		return ""
	}
	if i := strings.IndexByte(rel, '/'); i >= 0 {
		rel = rel[:i]
	}
	if !isSafeName(rel) {
		return ""
	}
	return rel
}

// loadEnv reads KEY=VALUE pairs for a project (empty map if none).
func loadEnv(project string) map[string]string {
	m := map[string]string{}
	f, err := os.Open(envFilePath(project))
	if err != nil {
		return m
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024) // allow long values
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		i := strings.IndexByte(line, '=')
		if i <= 0 {
			continue
		}
		key := strings.TrimSpace(line[:i])
		val := line[i+1:]
		m[key] = val
	}
	return m
}

// saveEnv writes the env file (0600), keeping only valid keys.
func saveEnv(project string, vars map[string]string) error {
	if err := os.MkdirAll(envDir(), 0700); err != nil {
		return err
	}
	keys := make([]string, 0, len(vars))
	for k := range vars {
		if envKeyRe.MatchString(k) {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("# Generated by Sixter — environment for " + project + "\n")
	for _, k := range keys {
		v := strings.ReplaceAll(vars[k], "\n", " ") // keep one var per line
		b.WriteString(k + "=" + v + "\n")
	}
	return atomicWriteFile(envFilePath(project), []byte(b.String()), 0600)
}

// GET  /api/env/<project>        → {vars:{...}}
// POST /api/env/<project> {vars} → save + (if running) restart the service
func handleEnv(w http.ResponseWriter, r *http.Request) {
	if !requireAuth(w, r) {
		return
	}
	name := strings.TrimPrefix(r.URL.Path, "/api/env/")
	if !isSafeName(name) {
		http.Error(w, "invalid project name", http.StatusBadRequest)
		return
	}

	switch r.Method {
	case http.MethodGet:
		writeJSONResp(w, map[string]any{"vars": loadEnv(name)})

	case http.MethodPost:
		var req struct {
			Vars map[string]string `json:"vars"`
		}
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			http.Error(w, "invalid request", http.StatusBadRequest)
			return
		}
		// reject bad keys explicitly so the user gets feedback
		for k := range req.Vars {
			if !envKeyRe.MatchString(k) {
				http.Error(w, "invalid variable name: "+k+" (use letters, digits, underscore; can't start with a digit)", http.StatusBadRequest)
				return
			}
		}
		if err := saveEnv(name, req.Vars); err != nil {
			http.Error(w, "save failed: "+err.Error(), http.StatusInternalServerError)
			return
		}
		restarted := restartService(name)
		note := "saved — will apply on next deploy"
		if restarted {
			note = "saved and service restarted — variables are live"
		}
		writeJSONResp(w, map[string]any{"ok": true, "note": note, "restarted": restarted})

	default:
		http.Error(w, "GET or POST only", http.StatusMethodNotAllowed)
	}
}

// writeJSONResp is a tiny JSON helper (repo-server has no shared one).
func writeJSONResp(w http.ResponseWriter, v any) {
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(v)
}
