package wg

import (
	"fmt"
	"net"
	"sort"
	"strings"
)

/*
Overlay addressing.

The address range is a decision you only get to make once, because changing it
later breaks every deployed fleet. Sixter uses 100.64.0.0/10 — the RFC 6598
"shared address space" reserved for carrier-grade NAT.

Why not 10.0.0.0/8 or 192.168.0.0/16, the obvious choices: customers already
use them. A bare-metal rack on 10.0.0.0/8, or an AWS VPC on 10.x, would find
its own LAN routes fighting the overlay's — and the failure mode is a machine
that can reach its database until someone adds a subnet, then can't. 100.64/10
is routable, private, and almost never appears in a corporate network, which is
exactly why Tailscale chose it too.

Layout: one /16 per account (65k machines), one /32 per machine.

	100.64.<account>.<host>

Addresses are ASSIGNED and stored, never derived from a hash. Hashing looks
elegant and gives you a birthday collision at a few hundred machines — two
nodes sharing an overlay IP is a silent, extremely confusing outage.
*/

const (
	// OverlayCIDR is the whole Sixter overlay space.
	OverlayCIDR = "100.64.0.0/10"

	// DefaultPort is the UDP port WireGuard listens on. Fixed rather than
	// random so a firewall rule or port-forward can be written once and
	// documented, instead of changing on every restart.
	DefaultPort = 51820

	// MTU leaves room for the WireGuard header (60 bytes for IPv6-capable
	// paths) inside a 1500-byte Ethernet frame. Too high and packets are
	// silently dropped by a router that won't fragment — which presents as a
	// tunnel that handshakes fine and then hangs on the first large query
	// result. That symptom is miserable to diagnose, so be conservative.
	MTU = 1420

	// Keepalive holds NAT mappings open. Without it a peer behind NAT becomes
	// unreachable a minute or two after it goes idle, and only reappears when
	// it happens to send something — an intermittent database that works right
	// after deploy and fails overnight.
	Keepalive = 25
)

// Peer is one remote machine on the overlay.
type Peer struct {
	Name      string `json:"name"`       // human label, for logs and the UI
	PublicKey Key    `json:"public_key"` // never a private key
	// Endpoint is host:port where this peer can be reached, if it is reachable
	// at all. Empty means "we don't know" — the peer must dial us first, which
	// WireGuard handles: whoever can reach the other establishes the session
	// and traffic then flows both ways.
	Endpoint  string `json:"endpoint,omitempty"`
	OverlayIP string `json:"overlay_ip"` // its /32 on the overlay

	// Routes are additional subnets reachable THROUGH this peer — in practice
	// the pod network on that machine. Without them a container here has no
	// path to a container there, because the overlay would only carry traffic
	// addressed to the machines themselves.
	Routes []string `json:"routes,omitempty"`
}

// Config is one machine's complete view of the mesh.
type Config struct {
	PrivateKey Key    `json:"-"` // stays on the machine; never serialised
	OverlayIP  string `json:"overlay_ip"`
	ListenPort int    `json:"listen_port"`
	Peers      []Peer `json:"peers"`
}

// Render produces a wg-quick compatible configuration.
//
// AllowedIPs is the peer's /32 only. A wider mask would make WireGuard capture
// routes the machine needs for ordinary traffic — the classic way to lock
// yourself out of a remote server you're configuring over SSH.
func (c Config) Render() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by Sixter — do not edit; changes are overwritten\n")
	fmt.Fprintf(&b, "[Interface]\n")
	fmt.Fprintf(&b, "PrivateKey = %s\n", c.PrivateKey)
	fmt.Fprintf(&b, "Address = %s/32\n", c.OverlayIP)
	fmt.Fprintf(&b, "ListenPort = %d\n", c.ListenPort)
	fmt.Fprintf(&b, "MTU = %d\n", MTU)

	peers := append([]Peer(nil), c.Peers...)
	sort.Slice(peers, func(i, j int) bool { return peers[i].OverlayIP < peers[j].OverlayIP })
	for _, p := range peers {
		if !p.PublicKey.Valid() || p.OverlayIP == "" {
			continue // never write unvalidated input into a kernel config
		}
		fmt.Fprintf(&b, "\n# %s\n[Peer]\n", sanitizeComment(p.Name))
		fmt.Fprintf(&b, "PublicKey = %s\n", p.PublicKey)
		// AllowedIPs is both a routing table and an ACL in WireGuard: a packet
		// arriving from this peer is DROPPED unless its source falls inside
		// this list. So the peer's pod subnet must be here, or container
		// traffic is silently discarded after a successful handshake.
		allowed := []string{p.OverlayIP + "/32"}
		for _, r := range p.Routes {
			if validCIDR(r) {
				allowed = append(allowed, r)
			}
		}
		fmt.Fprintf(&b, "AllowedIPs = %s\n", strings.Join(allowed, ", "))
		if ep := sanitizeEndpoint(p.Endpoint); ep != "" {
			fmt.Fprintf(&b, "Endpoint = %s\n", ep)
		}
		fmt.Fprintf(&b, "PersistentKeepalive = %d\n", Keepalive)
	}
	return b.String()
}

// Fingerprint identifies a configuration's meaningful content, so the agent can
// tell whether the mesh actually changed and skip reconfiguring the interface
// when it hasn't. Reapplying on every heartbeat would reset handshakes and drop
// live database connections every ten seconds.
func (c Config) Fingerprint() string {
	parts := []string{c.OverlayIP, fmt.Sprint(c.ListenPort)}
	peers := append([]Peer(nil), c.Peers...)
	sort.Slice(peers, func(i, j int) bool { return peers[i].PublicKey < peers[j].PublicKey })
	for _, p := range peers {
		parts = append(parts, string(p.PublicKey)+"|"+p.OverlayIP+"|"+p.Endpoint+
			"|"+strings.Join(p.Routes, "+"))
	}
	return strings.Join(parts, ";")
}

// sanitizeComment strips anything that could break out of a config comment.
func sanitizeComment(s string) string {
	s = strings.NewReplacer("\n", " ", "\r", " ", "[", "(", "]", ")").Replace(s)
	if len(s) > 64 {
		s = s[:64]
	}
	return s
}

// sanitizeEndpoint accepts only a parseable host:port. Peer data is relayed
// through the gateway and lands in a file consumed by the kernel; an unchecked
// value is a config-injection primitive.
func sanitizeEndpoint(ep string) string {
	ep = strings.TrimSpace(ep)
	if ep == "" {
		return ""
	}
	host, port, err := net.SplitHostPort(ep)
	if err != nil {
		return ""
	}
	// The LAST gate before this reaches the kernel. It must apply the same
	// rule as endpoint selection, or a value stored before that rule existed
	// — an IPv6 address, a loopback — survives in the database and keeps being
	// written into peer configs long after the bug was fixed.
	if !IsRoutable(net.ParseIP(host)) {
		return ""
	}
	for _, c := range port {
		if c < '0' || c > '9' {
			return ""
		}
	}
	return net.JoinHostPort(host, port)
}

/* ─────────── address allocation (gateway side) ─────────── */

// AllocateIP returns the next free overlay address in an account's /16.
//
// taken maps overlay IP → owner id so an existing machine keeps its address
// across restarts and re-enrolments. Stability matters more than density here:
// a machine whose overlay IP changes silently breaks every pg_hba rule and
// connection string that referenced it.
func AllocateIP(accountIndex int, taken map[string]string, self string) (string, error) {
	if accountIndex < 0 || accountIndex > 255 {
		return "", fmt.Errorf("wg: account index %d out of range", accountIndex)
	}
	for ip, owner := range taken {
		if owner == self {
			return ip, nil // already has one — keep it
		}
	}
	// .1 is reserved so a gateway/coordinator can always be addressed.
	for host := 2; host <= 254; host++ {
		ip := fmt.Sprintf("100.64.%d.%d", accountIndex, host)
		if _, used := taken[ip]; !used {
			return ip, nil
		}
	}
	return "", fmt.Errorf("wg: no free address in 100.64.%d.0/24", accountIndex)
}

// InOverlay reports whether an address belongs to the Sixter overlay — used to
// distinguish overlay traffic from a customer's own LAN.
func InOverlay(ip string) bool {
	parsed := net.ParseIP(ip)
	if parsed == nil {
		return false
	}
	_, cidr, err := net.ParseCIDR(OverlayCIDR)
	if err != nil {
		return false
	}
	return cidr.Contains(parsed)
}


/* ─────────── pod networking ─────────── */

const (
	// PodCIDRBase is where per-machine pod subnets are carved from. Kept
	// separate from the machine range so a node's pod subnet can be advertised
	// as one route instead of a growing list of individual container /32s.
	PodCIDRBase = "100.68.0.0/14" // 100.68.0.0 – 100.71.255.255 → 1024 /24s

	// PodsPerNode is the size of each machine's slice. A /24 gives 253 usable
	// container addresses per machine, which is far past the point where CPU
	// or memory runs out first.
	PodsPerNode = 24 // prefix length
)

// AllocatePodCIDR returns the next free /24 for a machine.
//
// Assigned and stored rather than derived, for the same reason machine
// addresses are: a hash collides, and two machines sharing a pod subnet is a
// silent routing failure that only appears under load.
func AllocatePodCIDR(taken map[string]string, self string) (string, error) {
	for cidr, owner := range taken {
		if owner == self {
			return cidr, nil // keep the one we already have
		}
	}
	used := map[string]bool{}
	for cidr := range taken {
		used[cidr] = true
	}
	for b := 68; b <= 71; b++ {
		for c := 0; c <= 255; c++ {
			cidr := fmt.Sprintf("100.%d.%d.0/%d", b, c, PodsPerNode)
			if !used[cidr] {
				return cidr, nil
			}
		}
	}
	return "", fmt.Errorf("wg: no free pod subnet in %s", PodCIDRBase)
}

// GatewayIP returns the address the host holds on a pod subnet — always .1,
// the container's default route.
func GatewayIP(podCIDR string) string {
	ip, _, err := net.ParseCIDR(podCIDR)
	if err != nil {
		return ""
	}
	v4 := ip.To4()
	if v4 == nil {
		return ""
	}
	return fmt.Sprintf("%d.%d.%d.1", v4[0], v4[1], v4[2])
}

// PodIP returns the nth container address in a subnet (n starts at 2, since
// .0 is the network and .1 is the host gateway).
func PodIP(podCIDR string, n int) (string, error) {
	if n < 2 || n > 254 {
		return "", fmt.Errorf("wg: pod index %d out of range for a /24", n)
	}
	ip, _, err := net.ParseCIDR(podCIDR)
	if err != nil {
		return "", err
	}
	v4 := ip.To4()
	if v4 == nil {
		return "", fmt.Errorf("wg: pod subnet %s is not IPv4", podCIDR)
	}
	return fmt.Sprintf("%d.%d.%d.%d", v4[0], v4[1], v4[2], n), nil
}

func validCIDR(s string) bool {
	_, _, err := net.ParseCIDR(strings.TrimSpace(s))
	return err == nil
}


/* ─────────── reachability ─────────── */

// Dialable reports whether peers can open a connection TO this machine.
//
// The obvious test — "can I bind UDP 51820?" — is wrong, and wrong in the
// worst way: once our own interface is up it holds that port, so the machine
// declares itself unreachable on every restart after the first. The gateway
// then publishes no endpoint for it, peers have nothing to dial, and the mesh
// configures perfectly while never completing a handshake.
//
// What actually determines dialability is having a PUBLIC address. A VPS with
// a routable IP can be reached; a cloud VM behind NAT (AWS, GCP) cannot be,
// and must dial outward instead — which WireGuard handles, because the session
// is bidirectional once either side connects.
func Dialable() bool {
	ifaces, err := net.Interfaces()
	if err != nil {
		return false
	}
	for _, iface := range ifaces {
		if iface.Flags&net.FlagUp == 0 || iface.Flags&net.FlagLoopback != 0 {
			continue
		}
		if !physicalIface(iface.Name) {
			continue
		}
		addrs, aerr := iface.Addrs()
		if aerr != nil {
			continue
		}
		for _, a := range addrs {
			ipnet, ok := a.(*net.IPNet)
			if !ok {
				continue
			}
			if IsRoutable(ipnet.IP) {
				return true // a routable v4 address: peers can reach us here
			}
		}
	}
	return false
}

// physicalIface excludes our own overlay and any container/VM plumbing, whose
// addresses say nothing about how the outside world reaches this machine.
func physicalIface(name string) bool {
	n := strings.ToLower(name)
	for _, p := range []string{
		"lo", "docker", "br-", "veth", "virbr", "cni", "flannel",
		"cali", "tun", "tap", "sixter", "wg",
	} {
		if strings.HasPrefix(n, p) {
			return false
		}
	}
	return true
}


// PublicIPs returns this machine's own routable IPv4 addresses.
//
// A machine behind a reverse proxy or sharing a host with the coordinator
// cannot be identified by the address the gateway observes — that will be
// 127.0.0.1. It therefore reports its own public addresses as a candidate,
// which the gateway accepts only after checking they really are public.
func PublicIPs() []string {
	ifaces, err := net.Interfaces()
	if err != nil {
		return nil
	}
	var out []string
	for _, iface := range ifaces {
		if iface.Flags&net.FlagUp == 0 || iface.Flags&net.FlagLoopback != 0 {
			continue
		}
		if !physicalIface(iface.Name) {
			continue
		}
		addrs, aerr := iface.Addrs()
		if aerr != nil {
			continue
		}
		for _, a := range addrs {
			ipnet, ok := a.(*net.IPNet)
			if !ok {
				continue
			}
			if ip := ipnet.IP.To4(); ip != nil && IsRoutable(ip) {
				out = append(out, ip.String())
			}
		}
	}
	sort.Strings(out)
	return out
}

// IsRoutable reports whether an address is usable as a WireGuard endpoint.
//
// IPv4 ONLY, deliberately. Two traps live here:
//
//   - Loopback: a peer handed 127.0.0.1 dials itself forever while every other
//     signal looks correct.
//   - IPv6: net.IP.IsPrivate only classifies IPv4, so an IPv6 address sails
//     through every "is this private?" test and gets published as the endpoint.
//     A dual-stack VPS then advertises its v6 address to nodes that have no v6
//     route at all — AWS VPCs are v4-only unless you enable v6 explicitly — and
//     the handshake can never complete.
//
// Supporting v6 endpoints properly means checking that BOTH peers have working
// v6, which the coordinator cannot know. Until then, v4 is the interoperable
// choice.
func IsRoutable(ip net.IP) bool {
	if ip == nil {
		return false
	}
	v4 := ip.To4()
	if v4 == nil {
		return false // IPv6: not assumed reachable from every peer
	}
	return !v4.IsLoopback() && !v4.IsPrivate() && !v4.IsUnspecified() &&
		!v4.IsLinkLocalUnicast() && !v4.IsMulticast()
}
